// Writes the "Verify" preset as JSON for the web guide (web/src/data/verify.json):
// the counter pins and step, the bursts, and example windows as edge lists.
//
// It builds the same frame as the firmware (src/core/verify_frame.cpp), so the
// waveforms in the lessons are exactly what the board outputs. Built and run
// by the host test project (tests/CMakeLists.txt); a ctest check fails if the
// committed JSON is out of date.
//
//   usage: export_verify <output.json>

#include <cstdio>
#include <vector>

#include "core/verify_frame.h"
#include "signal_config.h"

namespace {

constexpr uint32_t kSysHz = 150000000;

double ns(double cycles) { return cycles * 1e9 / kSysHz; }

// One example window: the given pins, as their level at the window start plus
// toggle times in ns relative to the window start.
void write_example(FILE* f, const verify_frame::Frame& frame, const char* label, const char* title, unsigned first_pin,
                   unsigned pin_count, double start, double end, bool last) {
    std::fprintf(f, "      {\"label\": \"%s\", \"title\": \"%s\", \"durationNs\": %.9g, \"traces\": [", label, title,
                 ns(end - start));
    for (unsigned p = first_pin; p < first_pin + pin_count; ++p) {
        const wave::PinWave& w = frame.pins[p];
        const uint32_t s = static_cast<uint32_t>(start);
        const char* role = p == verify_frame::kBurstPin ? "burst" : "bit";
        std::fprintf(f, "%s\n        {\"gpio\": %u, \"role\": \"%s\", \"initial\": %d, \"togglesNs\": [",
                     p == first_pin ? "" : ",", pins::kTimelineBase + p, role, w.level_at(s) ? 1 : 0);
        bool first_t = true;
        for (size_t i = 0; i < w.count; ++i) {
            const uint32_t t = w.toggles[i];
            if (t <= s || t >= end) continue;
            std::fprintf(f, "%s%.9g", first_t ? "" : ", ", ns(t - start));
            first_t = false;
        }
        std::fprintf(f, "]}");
    }
    std::fprintf(f, "\n      ]}%s\n", last ? "" : ",");
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 2) {
        std::fprintf(stderr, "usage: %s <output.json>\n", argv[0]);
        return 2;
    }
    const config::VerifyConfig& c = config::kVerify;
    static std::vector<uint32_t> pool(verify_frame::kPoolSize);
    static verify_frame::Frame frame;
    if (const char* error = verify_frame::build(frame, c, kSysHz, pool.data())) {
        std::fprintf(stderr, "verify frame: %s\n", error);
        return 1;
    }
    FILE* f = std::fopen(argv[1], "w");
    if (f == nullptr) {
        std::perror(argv[1]);
        return 1;
    }
    const double step = static_cast<double>(c.counter_step_ns) * kSysHz / 1e9;

    std::fprintf(f, "{\n  \"_comment\": \"Generated by tools/export_verify.cpp from src/signal_config.h. Do not edit.\",\n");
    std::fprintf(f, "  \"frameMs\": %.9g,\n", ns(frame.frame_cycles) / 1e6);
    std::fprintf(f, "  \"pins\": [\n");
    for (unsigned p = 0; p < verify_frame::kPinCount; ++p) {
        if (p == verify_frame::kBurstPin) {
            std::fprintf(f, "    {\"gpio\": %u, \"role\": \"burst\", \"name\": \"Frequency bursts\"}\n",
                         pins::kTimelineBase + p);
        } else {
            std::fprintf(f, "    {\"gpio\": %u, \"role\": \"bit\", \"bit\": %u, \"name\": \"Counter bit %u\"},\n",
                         pins::kTimelineBase + p, p, p);
        }
    }
    std::fprintf(f, "  ],\n");
    std::fprintf(f, "  \"counter\": {\"stepNs\": %u, \"bits\": %u},\n", c.counter_step_ns, c.counter_bits);
    std::fprintf(f, "  \"bursts\": [\n");
    for (size_t i = 0; i < frame.window_count; ++i) {
        const auto& w = frame.windows[i];
        std::fprintf(f, "    {\"hz\": %.9g, \"periods\": %u, \"startNs\": %.9g, \"endNs\": %.9g}%s\n", c.burst_hz[i],
                     c.burst_periods, ns(w.start), ns(w.end), i + 1 < frame.window_count ? "," : "");
    }
    std::fprintf(f, "  ],\n");
    std::fprintf(f, "  \"examples\": [\n");
    // The first 64 steps of the count, on the 8 lowest bits: what an 8-input analyzer sees.
    write_example(f, frame, "counter", "Counter, bits 0 to 7", 0, 8, 0, 64 * step, false);
    const auto& first = frame.windows[0];
    const auto& last = frame.windows[frame.window_count - 1];
    write_example(f, frame, "bursts", "All bursts", verify_frame::kBurstPin, 1, first.start - step,
                  last.end + step, true);
    std::fprintf(f, "  ]\n}\n");
    std::fclose(f);
    return 0;
}
