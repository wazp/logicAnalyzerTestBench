#!/usr/bin/env python3
"""Compiles the built web guide into flash data for the firmware's web server.

Input:  web/dist/index.html (one self-contained file, built by Vite)
Output: web_page.inc, included by src/net/http_server.cpp

The page is gzip compressed (about 23 KB instead of 67 KB) and served as is
with "Content-Encoding: gzip"; every browser decompresses it. The server
writes the HTTP headers itself, so only the body is stored here.

usage: prepare_web_content.py <dist/index.html> <output web_page.inc>
"""

import gzip
import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    source = Path(sys.argv[1])
    output = Path(sys.argv[2])

    # mtime=0 keeps the output byte-identical between builds.
    page = gzip.compress(source.read_bytes(), compresslevel=9, mtime=0)
    rows = []
    for i in range(0, len(page), 16):
        rows.append("    " + "".join(f"0x{b:02x}," for b in page[i : i + 16]))

    out = [
        "/* Generated by tools/prepare_web_content.py. Do not edit. */",
        f"/* {source.name}: {source.stat().st_size} bytes, gzip compressed to {len(page)} bytes */",
        "static const unsigned char kWebPageGzip[] = {",
        *rows,
        "};",
        "",
    ]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
