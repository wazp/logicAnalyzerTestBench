#!/usr/bin/env python3
"""Compiles the built web guide into flash data for the lwIP web server.

Input:  web/dist/index.html (one self-contained file, built by Vite)
Output: pico_fsdata.inc, included by lwIP's fs.c via HTTPD_FSDATA_FILE
        (see src/net/lwipopts.h)

Two files are served:
  /guide     the guide, gzip compressed (about 20 KB instead of 56 KB)
  /404.html  a redirect to /guide. lwIP answers every other URL with this,
             including "/", because there is no index file.

Redirecting everything except /guide is what makes the captive portal work.
After joining a network, phones fetch a known URL to check for internet.
Stock Android asks for /generate_204, but a Samsung Galaxy S24 (One UI) was
seen asking for "/", so a guide served at "/" answered its check with a
normal page. The phone then decided the network had no internet, offered
"Connect this time", and kept browsers off it. A redirect marks the network
as a sign-in portal instead. Typing http://<ip>/ still works, it redirects
to /guide.

Each entry stores the complete HTTP response header followed by the body, the
same layout the SDK's makefsdata.py produces. We generate it ourselves so the
headers are exact (CRLF line endings, Content-Encoding: gzip), which
makefsdata.py's .response files cannot guarantee.

usage: prepare_web_content.py <dist/index.html> <output pico_fsdata.inc> <access point ip>
"""

import gzip
import sys
from pathlib import Path

SERVER = "lwIP"


def http_header(status: str, headers: list[str]) -> bytes:
    lines = [f"HTTP/1.0 {status}", f"Server: {SERVER}", *headers]
    return ("\r\n".join(lines) + "\r\n\r\n").encode("ascii")


def c_bytes(data: bytes) -> str:
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + "".join(f"0x{b:02x}," for b in data[i : i + 16]))
    return "\n".join(rows)


def entry(var: str, path: str, header: bytes, body: bytes) -> tuple[str, str, int]:
    # The file name is NUL terminated and padded to 4 bytes, as fs.c expects.
    name = path.encode("ascii") + b"\0"
    name += b"\0" * (-len(name) % 4)
    data = name + header + body
    source = f"/* {path}: {len(header)} byte header, {len(body)} byte body */\n"
    source += f"static const unsigned char data_{var}[] = {{\n{c_bytes(data)}\n}};\n"
    return var, source, len(name)


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    source = Path(sys.argv[1])
    output = Path(sys.argv[2])
    ip = sys.argv[3]

    # mtime=0 keeps the output byte-identical between builds.
    page = gzip.compress(source.read_bytes(), compresslevel=9, mtime=0)
    entries = [
        entry(
            "guide",
            "/guide",
            http_header(
                "200 OK",
                [
                    f"Content-Length: {len(page)}",
                    "Content-Type: text/html; charset=utf-8",
                    "Content-Encoding: gzip",
                    "Cache-Control: no-cache",
                ],
            ),
            page,
        ),
        entry(
            "404_html",
            "/404.html",
            http_header("302 Found", [f"Location: http://{ip}/guide", "Content-Length: 0"]),
            b"",
        ),
    ]

    out = ["/* Generated by tools/prepare_web_content.py. Do not edit. */", '#include "lwip/apps/fs.h"', ""]
    for _, src, _ in entries:
        out.append(src)
    previous = "NULL"
    for var, _, name_size in entries:
        out.append(
            f"const struct fsdata_file file_{var}[] = {{{{\n"
            f"    {previous},\n"
            f"    data_{var},\n"
            f"    data_{var} + {name_size},\n"
            f"    sizeof(data_{var}) - {name_size},\n"
            f"    FS_FILE_FLAGS_HEADER_INCLUDED | FS_FILE_FLAGS_HEADER_PERSISTENT,\n"
            f"}}}};\n"
        )
        previous = f"file_{var}"
    out.append(f"#define FS_ROOT {previous}")
    out.append(f"#define FS_NUMFILES {len(entries)}")

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
