// Writes the "Video and input" preset as JSON for the web guide
// (web/src/data/video.json): pins, VGA timing, the NES buttons and PS/2
// bytes a learner should find, and example windows as edge lists.
//
// It builds the same frame as the firmware (src/core/video_frame.cpp), so the
// waveforms in the lessons are exactly what the board outputs. Built and run
// by the host test project (tests/CMakeLists.txt); a ctest check fails if the
// committed JSON is out of date.
//
//   usage: export_video <output.json>

#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

#include "core/protocols/nes.h"
#include "core/protocols/ps2.h"
#include "core/protocols/vga.h"
#include "core/video_frame.h"
#include "signal_config.h"

namespace {

constexpr uint32_t kSysHz = 150000000;

double ns(double cycles) { return cycles * 1e9 / kSysHz; }

struct PinInfo {
    video_frame::Pin pin;
    const char* part;  // "vga", "nes" or "ps2"
    const char* role;
    const char* name;
    bool idle_high;  // Level between transactions (blanking for the colors).
};

constexpr PinInfo kPins[] = {
    {video_frame::kHsync, "vga", "hsync", "VGA HSYNC", true},
    {video_frame::kVsync, "vga", "vsync", "VGA VSYNC", true},
    {video_frame::kRed, "vga", "red", "VGA red", false},
    {video_frame::kGreen, "vga", "green", "VGA green", false},
    {video_frame::kBlue, "vga", "blue", "VGA blue", false},
    {video_frame::kNesLatch, "nes", "latch", "NES latch", false},
    {video_frame::kNesClock, "nes", "clock", "NES clock", true},
    {video_frame::kNesData, "nes", "data", "NES data (controller)", false},
    {video_frame::kPs2Clock, "ps2", "clock", "PS/2 clock (keyboard)", true},
    {video_frame::kPs2Data, "ps2", "data", "PS/2 data (keyboard)", true},
};

std::string numbers(const std::vector<double>& values) {
    std::string out = "[";
    for (size_t i = 0; i < values.size(); ++i) {
        char b[32];
        std::snprintf(b, sizeof(b), "%s%.9g", i ? ", " : "", values[i]);
        out += b;
    }
    return out + "]";
}

// One example window: every pin of the part, as its level at the window start
// plus toggle times in ns relative to the window start.
void write_example(FILE* f, const video_frame::Frame& frame, const char* part, const char* label, const char* title,
                   double start, double end, bool last) {
    std::fprintf(f, "        {\"label\": \"%s\", \"title\": \"%s\", \"durationNs\": %.9g, \"traces\": [", label, title,
                 ns(end - start));
    bool first = true;
    for (const auto& p : kPins) {
        if (std::strcmp(p.part, part) != 0) continue;
        const wave::PinWave& w = frame.pins[p.pin];
        const uint32_t s = static_cast<uint32_t>(start);
        std::fprintf(f, "%s\n          {\"gpio\": %u, \"role\": \"%s\", \"initial\": %d, \"togglesNs\": [",
                     first ? "" : ",", pins::kTimelineBase + p.pin, p.role, w.level_at(s) ? 1 : 0);
        bool first_t = true;
        for (size_t i = 0; i < w.count; ++i) {
            const uint32_t t = w.toggles[i];
            if (t <= s || t >= end) continue;
            std::fprintf(f, "%s%.9g", first_t ? "" : ", ", ns(t - start));
            first_t = false;
        }
        std::fprintf(f, "]}");
        first = false;
    }
    std::fprintf(f, "\n        ]}%s\n", last ? "" : ",");
}

std::vector<const video_frame::Window*> windows(const video_frame::Frame& frame, const char* part, const char* label) {
    std::vector<const video_frame::Window*> out;
    for (size_t i = 0; i < frame.window_count; ++i) {
        if (!std::strcmp(frame.windows[i].protocol, part) && !std::strcmp(frame.windows[i].label, label)) {
            out.push_back(&frame.windows[i]);
        }
    }
    return out;
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 2) {
        std::fprintf(stderr, "usage: %s <output.json>\n", argv[0]);
        return 2;
    }
    const config::VideoConfig& c = config::kVideo;
    static std::vector<uint32_t> pool(video_frame::kPoolSize);
    static video_frame::Frame frame;
    if (const char* error = video_frame::build(frame, c, kSysHz, pool.data())) {
        std::fprintf(stderr, "video frame: %s\n", error);
        return 1;
    }
    FILE* f = std::fopen(argv[1], "w");
    if (f == nullptr) {
        std::perror(argv[1]);
        return 1;
    }
    const proto::VgaTiming vga = video_frame::vga_timing(c);
    const double px = c.pixel_cycles;
    const double line = vga.line_cycles();
    const double us = kSysHz / 1e6;

    std::fprintf(f, "{\n  \"_comment\": \"Generated by tools/export_video.cpp from src/signal_config.h. Do not edit.\",\n");
    std::fprintf(f, "  \"frameMs\": %.9g,\n", ns(frame.frame_cycles) / 1e6);
    std::fprintf(f, "  \"pins\": [\n");
    for (size_t i = 0; i < sizeof(kPins) / sizeof(kPins[0]); ++i) {
        const auto& p = kPins[i];
        std::fprintf(f, "    {\"gpio\": %u, \"part\": \"%s\", \"role\": \"%s\", \"name\": \"%s\", \"idleHigh\": %s}%s\n",
                     pins::kTimelineBase + p.pin, p.part, p.role, p.name,
                     p.idle_high ? "true" : "false", i + 1 < sizeof(kPins) / sizeof(kPins[0]) ? "," : "");
    }
    std::fprintf(f, "  ],\n");
    std::fprintf(f, "  \"unusedGpios\": [%u, %u, %u],\n", pins::kTimelineBase + video_frame::kUnused20,
                 pins::kTimelineBase + video_frame::kUnused21, pins::kTimelineBase + video_frame::kUnused22);

    // --- VGA ---
    {
        std::fprintf(f, "  \"vga\": {\n");
        std::fprintf(f, "    \"pixelHz\": %.9g, \"pixelNs\": %.9g, \"lineNs\": %.9g, \"frameNs\": %.9g,\n",
                     kSysHz / px, ns(px), ns(line), ns(vga.frame_cycles()));
        std::fprintf(f, "    \"h\": {\"visible\": %u, \"front\": %u, \"sync\": %u, \"back\": %u},\n", c.h_visible,
                     c.h_front, c.h_sync, c.h_back);
        std::fprintf(f, "    \"v\": {\"visible\": %u, \"front\": %u, \"sync\": %u, \"back\": %u},\n", c.v_visible,
                     c.v_front, c.v_sync, c.v_back);
        std::fprintf(f, "    \"bars\": [");
        for (unsigned b = 0; b < proto::kVgaBarCount; ++b) {
            std::fprintf(f, "%s{\"name\": \"%s\", \"r\": %d, \"g\": %d, \"b\": %d}", b ? ", " : "",
                         proto::kVgaBarNames[b], proto::kVgaBars[b].r, proto::kVgaBars[b].g, proto::kVgaBars[b].b);
        }
        std::fprintf(f, "],\n    \"examples\": [\n");
        // A line from the middle of the picture, with the sync pulses on both sides.
        const double l = line * 99;
        write_example(f, frame, "vga", "line", "One line", l + px * 600, l + line + px * 700, false);
        // The end of the picture and the vertical sync pulse.
        write_example(f, frame, "vga", "vsync", "Vertical blanking", line * 476, line * 500, true);
        std::fprintf(f, "    ]\n  },\n");
    }

    // --- NES controller ---
    {
        const auto reads = windows(frame, "nes", "read");
        std::fprintf(f, "  \"nes\": {\n");
        std::fprintf(f, "    \"buttonNames\": [");
        for (unsigned n = 0; n < 8; ++n) std::fprintf(f, "%s\"%s\"", n ? ", " : "", proto::kNesButtonNames[n]);
        std::fprintf(f, "],\n    \"buttons\": [%u, %u], \"readLine\": %u,\n", c.nes_buttons[0], c.nes_buttons[1],
                     c.v_visible);
        std::vector<double> starts;
        for (const auto* w : reads) starts.push_back(ns(w->start) / 1e6);
        std::fprintf(f, "    \"latchUs\": %u, \"clockPeriodUs\": %u, \"firstClockUs\": %u, \"readStartsMs\": %s,\n",
                     c.nes_latch_us, c.nes_clock_period_us, c.nes_first_clock_us, numbers(starts).c_str());
        std::fprintf(f, "    \"examples\": [\n");
        write_example(f, frame, "nes", "read1", "First read", reads[0]->start - 10 * us, reads[0]->end + 16 * us, false);
        write_example(f, frame, "nes", "read2", "Second read", reads[1]->start - 10 * us, reads[1]->end + 16 * us, true);
        std::fprintf(f, "    ]\n  },\n");
    }

    // --- PS/2 keyboard ---
    {
        const auto* make = windows(frame, "ps2", "make")[0];
        const auto* brk = windows(frame, "ps2", "break")[0];
        std::fprintf(f, "  \"ps2\": {\n");
        std::fprintf(f, "    \"clockHz\": %u, \"bitNs\": %.9g, \"key\": %u, \"keyName\": \"A\", \"breakPrefix\": %u,\n",
                     c.ps2_clock_hz, 1e9 / c.ps2_clock_hz, c.ps2_key, proto::kPs2Break);
        std::fprintf(f, "    \"makeStartMs\": %.9g, \"breakStartMs\": %.9g, \"byteGapUs\": %u,\n",
                     ns(make->start) / 1e6, ns(brk->start) / 1e6, c.ps2_byte_gap_us);
        std::fprintf(f, "    \"examples\": [\n");
        write_example(f, frame, "ps2", "make", "Key down", make->start - 100 * us, make->end + 100 * us, false);
        write_example(f, frame, "ps2", "break", "Key up", brk->start - 100 * us, brk->end + 100 * us, true);
        std::fprintf(f, "    ]\n  }\n");
    }

    std::fprintf(f, "}\n");
    std::fclose(f);
    return 0;
}
