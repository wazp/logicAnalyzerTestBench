// Writes the default signal set as JSON for the web guide (web/src/data/signals.json).
//
// It uses the same config and timing code as the firmware, so the web guide
// always shows the values the board really produces after rounding to whole
// clock cycles. Built and run by the host test project (tests/CMakeLists.txt);
// a ctest check fails if the committed JSON is out of date.
//
//   usage: export_signals <output.json>

#include <cstdio>
#include <string>

#include "signal_config.h"

namespace {

// clk_sys the firmware runs at (Pico SDK default for RP2350).
constexpr uint32_t kSysHz = 150000000;

double cycles_to_ns(uint64_t cycles) { return static_cast<double>(cycles) * 1e9 / kSysHz; }

// One output signal as a repeating list of (level, duration) segments. This
// is the shape the web app uses to draw and sample every signal type.
struct Segment {
    bool level;
    double ns;
};

void write_segments(FILE* f, const Segment* segs, size_t count) {
    std::fprintf(f, "      \"segments\": [");
    for (size_t i = 0; i < count; ++i) {
        std::fprintf(f, "%s{\"level\": %d, \"ns\": %.9g}", i ? ", " : "", segs[i].level ? 1 : 0, segs[i].ns);
    }
    std::fprintf(f, "]\n");
}

void write_signal_head(FILE* f, bool first, unsigned gpio, const char* name, const char* kind,
                       const std::string& peripheral, double requested_hz, double actual_hz, double duty) {
    std::fprintf(f, "%s    {\n", first ? "" : ",\n");
    std::fprintf(f, "      \"gpio\": %u,\n", gpio);
    std::fprintf(f, "      \"name\": \"%s\",\n", name);
    std::fprintf(f, "      \"kind\": \"%s\",\n", kind);
    std::fprintf(f, "      \"peripheral\": \"%s\",\n", peripheral.c_str());
    if (requested_hz > 0.0) {
        std::fprintf(f, "      \"requestedHz\": %.9g,\n", requested_hz);
    } else {
        std::fprintf(f, "      \"requestedHz\": null,\n");
    }
    std::fprintf(f, "      \"actualHz\": %.9g,\n", actual_hz);
    std::fprintf(f, "      \"dutyPercent\": %.9g,\n", duty);
}

// A segment pattern played by pattern.pio. Returns false (after printing why) if it does not encode.
bool write_pattern(FILE* f, unsigned gpio, const char* name, const char* kind, unsigned pio_index, unsigned sm,
                   const timing::PatternSegment* pattern, size_t count) {
    constexpr size_t kMaxSegments = 64;  // As in src/hw/pattern_output.cpp.
    uint32_t words[kMaxSegments];
    const auto e = timing::encode_pattern(kSysHz, pattern, count, words, kMaxSegments);
    if (!e.valid) {
        std::fprintf(stderr, "GP%u: %s\n", gpio, e.error);
        return false;
    }
    Segment segs[kMaxSegments];
    uint64_t high_cycles = 0;
    for (size_t i = 0; i < e.word_count; ++i) {
        const uint64_t cycles = (words[i] >> 1) + timing::kPatternSegmentOverheadCycles;
        segs[i] = {(words[i] & 1u) != 0, cycles_to_ns(cycles)};
        if (segs[i].level) {
            high_cycles += cycles;
        }
    }
    const std::string per = "PIO" + std::to_string(pio_index) + " SM" + std::to_string(sm) + "+DMA";
    write_signal_head(f, false, gpio, name, kind, per, 0.0,
                      static_cast<double>(kSysHz) / static_cast<double>(e.total_cycles),
                      100.0 * static_cast<double>(high_cycles) / static_cast<double>(e.total_cycles));
    write_segments(f, segs, e.word_count);
    std::fprintf(f, "    }");
    return true;
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 2) {
        std::fprintf(stderr, "usage: %s <output.json>\n", argv[0]);
        return 2;
    }
    FILE* f = std::fopen(argv[1], "w");
    if (f == nullptr) {
        std::perror(argv[1]);
        return 1;
    }

    std::fprintf(f, "{\n");
    std::fprintf(f, "  \"_comment\": \"Generated by tools/export_signals.cpp from src/signal_config.h. Do not edit.\",\n");
    std::fprintf(f, "  \"clkSysHz\": %u,\n", kSysHz);
    std::fprintf(f, "  \"signals\": [\n");

    bool first = true;
    for (const auto& s : config::kSquareSignals) {
        const auto t = timing::compute_square_timing(kSysHz, s.freq_hz, s.duty_percent);
        if (!t.valid) {
            std::fprintf(stderr, "GP%u: %s\n", s.pin, t.error);
            return 1;
        }
        const std::string per = "PIO" + std::to_string(s.pio_index) + " SM" + std::to_string(s.sm);
        write_signal_head(f, first, s.pin, s.name, "square", per, s.freq_hz, t.actual_hz, t.actual_duty_percent);
        const Segment segs[] = {{true, cycles_to_ns(t.high_cycles)}, {false, cycles_to_ns(t.low_cycles)}};
        write_segments(f, segs, 2);
        std::fprintf(f, "    }");
        first = false;
    }

    // PWM duty pair: both channels of one slice.
    {
        const auto& p = config::kPwmPair;
        const auto t = timing::compute_pwm_timing(kSysHz, p.freq_hz);
        const unsigned slice = pins::pwm_slice_for(p.pin_a);
        const double period_ns = 1e9 / t.actual_hz;
        const unsigned gpios[] = {p.pin_a, p.pin_b};
        const char* names[] = {p.name_a, p.name_b};
        const double duties[] = {p.duty_a_percent, p.duty_b_percent};
        for (int i = 0; i < 2; ++i) {
            const uint32_t level = timing::pwm_level_for_duty(t, duties[i]);
            const double high_ns = timing::pwm_high_time_ns(t, level);
            const std::string per = "PWM" + std::to_string(slice) + (i == 0 ? " A" : " B");
            write_signal_head(f, false, gpios[i], names[i], "pwm", per, p.freq_hz, t.actual_hz,
                              100.0 * high_ns / period_ns);
            const Segment segs[] = {{true, high_ns}, {false, period_ns - high_ns}};
            write_segments(f, segs, 2);
            std::fprintf(f, "    }");
        }
    }

    // Short periodic pulse.
    {
        const auto& p = config::kPulse;
        const auto t = timing::compute_pwm_timing(kSysHz, p.freq_hz);
        const uint32_t level = timing::pwm_level_for_high_time_ns(t, p.high_ns);
        const double high_ns = timing::pwm_high_time_ns(t, level);
        const double period_ns = 1e9 / t.actual_hz;
        const unsigned slice = pins::pwm_slice_for(p.pin);
        const std::string per = "PWM" + std::to_string(slice) + (pins::pwm_is_channel_a(p.pin) ? " A" : " B");
        write_signal_head(f, false, p.pin, p.name, "pulse", per, p.freq_hz, t.actual_hz, 100.0 * high_ns / period_ns);
        const Segment segs[] = {{true, high_ns}, {false, period_ns - high_ns}};
        write_segments(f, segs, 2);
        std::fprintf(f, "    }");
    }

    // The GP9 pattern and the GP26 bouncing button, using the encoded cycle counts so rounding matches.
    if (!write_pattern(f, pins::kPattern, config::kPatternName, "pattern", config::kPatternPioIndex,
                       config::kPatternSm, config::kPatternSegments, config::kPatternSegmentCount) ||
        !write_pattern(f, pins::kBounce, config::kBounceName, "bounce", config::kBouncePioIndex, config::kBounceSm,
                       config::kBounceSegments, config::kBounceSegmentCount)) {
        return 1;
    }

    std::fprintf(f, "\n  ]\n}\n");
    std::fclose(f);
    return 0;
}
